import { describe, expect, it } from "vitest";

describe("reference formats", () => {
  it("validates admission references generated by the API", () => {
    expect(/^ADM-\d{4}-[A-Z0-9]{8}$/.test("ADM-2026-AB12CD34")).toBe(true);
    expect(/^ADM-\d{4}-[A-Z0-9]{8}$/.test("ADM-26-invalid")).toBe(false);
  });

  it("validates Paystack payment references", () => {
    expect(/^EDU-\d+-[A-Z0-9]{8}$/.test("EDU-1760000000000-AB12CD34")).toBe(true);
  });
});
